'use strict';
// Icon-generation guard (Phase 7C5.1). Locks the deterministic app-icon pipeline:
// the four owner-approved source SVGs are never mutated by generation, the
// generated platform assets have the right dimensions/entries and decode, the
// committed output matches a fresh regeneration (deterministic + in sync), and
// cyan opaque -- never yellow -- is the executable identity the build config uses.

const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const icons = require('../../scripts/build-icons.js');
const ROOT = path.resolve(__dirname, '..', '..');
const ASSETS = path.join(ROOT, 'assets');
const GEN = path.join(ASSETS, 'generated', 'icons');
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

// Parse an .ico into its directory entries, each with the embedded PNG blob.
function icoEntries(buf) {
  assert.equal(buf.readUInt16LE(0), 0, 'ico reserved');
  assert.equal(buf.readUInt16LE(2), 1, 'ico type = icon');
  const count = buf.readUInt16LE(4);
  const out = [];
  for (let i = 0; i < count; i++) {
    const b = 6 + i * 16;
    let w = buf.readUInt8(b); if (w === 0) w = 256;
    let h = buf.readUInt8(b + 1); if (h === 0) h = 256;
    const len = buf.readUInt32LE(b + 8);
    const off = buf.readUInt32LE(b + 12);
    out.push({ w, h, blob: buf.slice(off, off + len) });
  }
  return out;
}
const isPng = (b) => b.slice(1, 4).toString('latin1') === 'PNG';

test('the four owner-approved source SVGs exist', () => {
  for (const name of Object.values(icons.SOURCES)) {
    const p = path.join(ASSETS, name);
    assert.ok(fs.existsSync(p), `missing source ${name}`);
    assert.ok(fs.statSync(p).size > 0, `empty source ${name}`);
  }
});

test('generation does not mutate the source SVGs', () => {
  const before = Object.values(icons.SOURCES).map((n) => sha(fs.readFileSync(path.join(ASSETS, n))));
  icons.generate();
  const after = Object.values(icons.SOURCES).map((n) => sha(fs.readFileSync(path.join(ASSETS, n))));
  assert.deepEqual(after, before, 'source SVG bytes changed during generation');
});

test('generation is deterministic and the committed output is in sync', () => {
  // Snapshot committed generated bytes, regenerate, and require byte-identity.
  // This proves BOTH determinism (repeat run == prior run) and that the tree
  // committed to git matches what the generator produces right now.
  const files = fs.readdirSync(GEN, { recursive: true })
    .map((f) => path.join(GEN, f))
    .filter((p) => fs.statSync(p).isFile())
    .sort();
  const before = files.map((f) => [path.relative(GEN, f), sha(fs.readFileSync(f))]);
  icons.generate();
  const after = files.map((f) => [path.relative(GEN, f), sha(fs.readFileSync(f))]);
  assert.deepEqual(after, before, 'regeneration differs from committed output (non-deterministic or stale)');
});

test('all four variant ICOs exist with the expected multi-resolution entries', () => {
  for (const v of icons.VARIANTS) {
    const p = path.join(GEN, 'windows', icons.icoName(v.variant));
    assert.ok(fs.existsSync(p), `missing ico for ${v.variant}`);
    const entries = icoEntries(fs.readFileSync(p));
    assert.deepEqual(entries.map((e) => e.w).sort((a, b) => a - b), [...icons.ICO_SIZES].sort((a, b) => a - b),
      `${v.variant} ico entry sizes`);
    for (const e of entries) {
      assert.ok(isPng(e.blob), `${v.variant} ${e.w}px entry is not PNG`);
      assert.equal(e.blob.readUInt32BE(16), e.w, `${v.variant} ${e.w}px PNG width`);
      assert.equal(e.blob.readUInt32BE(20), e.h, `${v.variant} ${e.w}px PNG height`);
      assert.equal(e.w, e.h, `${v.variant} ${e.w}px not square`);
    }
  }
});

test('linux PNG set exists at the expected square dimensions and decodes', () => {
  for (const size of icons.PNG_SIZES) {
    const p = path.join(GEN, 'linux', `${size}x${size}.png`);
    assert.ok(fs.existsSync(p), `missing linux/${size}`);
    const buf = fs.readFileSync(p);
    assert.ok(isPng(buf) && buf.length > 0, `linux/${size} not a nonempty PNG`);
    assert.equal(icons.pngSize(buf).width, size);
    assert.equal(icons.pngSize(buf).height, size);
  }
});

test('runtime window icon and About logo exist and decode', () => {
  const icon = fs.readFileSync(path.join(GEN, 'runtime', 'icon.png'));
  assert.ok(isPng(icon), 'runtime icon.png not a PNG');
  assert.equal(icons.pngSize(icon).width, 256);
  const logo = fs.readFileSync(path.join(GEN, 'runtime', 'about-logo.png'));
  assert.ok(isPng(logo), 'about-logo.png not a PNG');
  assert.equal(icons.pngSize(logo).width, 256);
});

test('electron build config points at the cyan generated ICO (never yellow)', () => {
  const pkg = require(path.join(ROOT, 'package.json'));
  const iconPath = pkg.build.win.icon;
  assert.equal(iconPath, 'assets/generated/icons/windows/wrl-forge-cyan.ico',
    'build.win.icon must be the cyan generated ICO');
  assert.ok(!/yellow/i.test(iconPath), 'the executable identity must not be a yellow icon');
  assert.ok(fs.existsSync(path.join(ROOT, iconPath)), 'build.win.icon path does not resolve on disk');
});

test('all four choosable ICOs ship in the packaged app via extraResources', () => {
  const pkg = require(path.join(ROOT, 'package.json'));
  const er = pkg.build.extraResources;
  assert.ok(Array.isArray(er) && er.some((e) => e.from === 'assets/generated/icons/windows' && e.to === 'icons'),
    'extraResources must bundle the windows ICO folder as resources/icons');
});

test('the runtime window-icon path referenced by main.js resolves', () => {
  const main = fs.readFileSync(path.join(ROOT, 'main.js'), 'utf8');
  assert.ok(/generated['"\s,]+.*icons['"\s,]+.*runtime['"\s,]+.*icon\.png/s.test(main)
    || main.includes("'runtime', 'icon.png'"), 'main.js should set the BrowserWindow icon to runtime/icon.png');
  assert.ok(fs.existsSync(path.join(GEN, 'runtime', 'icon.png')), 'runtime icon.png missing');
});

test('resolvePrimaryIcon defaults to cyan and honors approved variants only', () => {
  assert.equal(icons.resolvePrimaryIcon(undefined).variant, 'cyan');
  assert.equal(icons.resolvePrimaryIcon('').variant, 'cyan');
  assert.equal(icons.resolvePrimaryIcon('nonsense').variant, 'cyan');
  assert.equal(icons.resolvePrimaryIcon('nonsense').isDefault, true);
  assert.equal(icons.resolvePrimaryIcon('yellow').variant, 'yellow');
  assert.equal(icons.resolvePrimaryIcon('yellow').isDefault, false);
  assert.equal(icons.resolvePrimaryIcon('YELLOW-TRANSPARENT').variant, 'yellow-transparent');
  assert.equal(icons.resolvePrimaryIcon('cyan').isDefault, true);
});

test('MANIFEST records cyan as the primary variant and lists source hashes', () => {
  const m = JSON.parse(fs.readFileSync(path.join(GEN, 'MANIFEST.json'), 'utf8'));
  assert.equal(m.primaryVariant, 'cyan');
  assert.equal(m.primaryIcon, 'assets/generated/icons/windows/wrl-forge-cyan.ico');
  for (const name of Object.values(icons.SOURCES)) {
    assert.match(m.sourceHashes[name], /^[0-9a-f]{64}$/, `manifest missing hash for ${name}`);
  }
});
